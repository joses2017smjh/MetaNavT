def _start(name: str) -> str:
    return f"<!-- {name}:start (generated by `make bench-table` from {SOURCES.get(name, 'bench/results/main.json')}; do not edit by hand) -->"


def _end(name: str) -> str:
    return f"<!-- {name}:end -->"


def _rows(blob: dict) -> dict[str, dict]:
    return {row["config"]: row for row in blob.get("results", [])}


def _ci(row: dict | None, metric: str) -> str:
    block = (row or {}).get("ci", {}).get(metric) if row else None
    if not block:
        return "—"
    return f"{block['mean']:.3f} [{block['lo']:.3f}, {block['hi']:.3f}]"


def _delta(block: dict | None) -> str:
    if not block:
        return "—"
    return f"{block['delta']:+.3f} [{block['lo']:+.3f}, {block['hi']:+.3f}]"


def _zero_note(block: dict | None) -> str:
    if not block:
        return ""
    return "the interval covers zero" if block["lo"] <= 0.0 <= block["hi"] else "the interval excludes zero"


def components_excluding_zero(blob: dict) -> list[str]:
    """Added components whose nDCG@10 gain over the previous row has a CI above zero."""
    rows = _rows(blob)
    out = []
    for name in ADDED_COMPONENTS:
        block = ((rows.get(name) or {}).get("delta_vs_previous") or {}).get("ndcg@10")
        if block and block["lo"] > 0.0:
            out.append(name.split("+")[-1])
    return out


def headline(blob: dict) -> str:
    rows = _rows(blob)
    full, bm25 = rows.get(FULL), rows.get(REFERENCE)
    if full is None or bm25 is None:
        return f"Fixture benchmark: {len(rows)} configs (no {FULL} / {REFERENCE} rows to summarise)."
    r_full, r_bm25 = full["retrieval"], bm25["retrieval"]
    d_bm25 = (full.get("delta_vs_bm25_only") or {})
    d_prev = (full.get("delta_vs_previous") or {})
    parts = [
        f"On the frozen fixture ({blob['n_gold']} questions over {blob['n_files']} files; hash embeddings, "
        f"overlap reranker) the full pipeline scores nDCG@10 {_ci(full, 'ndcg@10')} and Recall@10 "
        f"{_ci(full, 'recall@10')}; BM25 alone scores nDCG@10 {_ci(bm25, 'ndcg@10')} and Recall@10 "
        f"{_ci(bm25, 'recall@10')}.",
        f"Paired delta, full pipeline minus BM25: nDCG@10 {_delta(d_bm25.get('ndcg@10'))} "
        f"({_zero_note(d_bm25.get('ndcg@10'))}), Recall@10 {_delta(d_bm25.get('recall@10'))} "
        f"({_zero_note(d_bm25.get('recall@10'))}).",
    ]
    if d_prev.get("reference") == ROUTER_ON:
        parts.append(
            f"Staleness Tier 1 on vs off: nDCG@10 {_delta(d_prev.get('ndcg@10'))} "
            f"({_zero_note(d_prev.get('ndcg@10'))})."
        )
    excl = components_excluding_zero(blob)
    parts.append(
        "Of the added components (rerank, router, staleness), the nDCG@10 gain over the previous row "
        f"that excludes zero: {', '.join(excl) if excl else 'none'}."
    )
    off, on = rows.get(ROUTER_OFF), rows.get(ROUTER_ON)
    if off and on:
        cat_off = off["retrieval"]["by_category"].get("exact_path", {})
        cat_on = on["retrieval"]["by_category"].get("exact_path", {})
        if cat_off and cat_on:
            parts.append(
                f"The router's exact-path gain, nDCG@10 {cat_off['ndcg@10']:.3f} → {cat_on['ndcg@10']:.3f}, "
                f"rests on n = {int(cat_on['n'])} questions."
            )
    rand = r_full.get("random_recall@50")
    if rand is not None:
        parts.append(
            f"Recall@50 is {r_full['recall@50']:.3f} against {rand:.3f} for a random list of the same length: "
            f"with {r_full['mean_unique_paths@50']:.0f} unique files in a top-50 over {blob['n_files']}, "
            f"that metric mostly measures list length."
        )
    return " ".join(parts)


def table(blob: dict) -> str:
    rows = list(blob.get("results", []))
    boot = blob.get("bootstrap") or {}
    lines = [
        "| config | nDCG@10 [95% CI] | Recall@10 [95% CI] | random list @10 | Recall@50 | random list @50 | unique files in top 50 | MRR@10 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        r = row["retrieval"]
        rand50 = r.get("random_recall@50")
        rand10 = r.get("random_recall@10")
        fmt = lambda v: "—" if v is None else f"{v:.3f}"  # noqa: E731
        lines.append(
            f"| {row['config']} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | {fmt(rand10)} | {r['recall@50']:.3f} | "
            f"{fmt(rand50)} | {r.get('mean_unique_paths@50', 0):.1f} | {r['mrr@10']:.3f} |"
        )
    lines += [
        "",
        "Paired deltas (same bootstrap resamples for both sides):",
        "",
        "| config | Δ nDCG@10 vs bm25_only [95% CI] | Δ Recall@10 vs bm25_only [95% CI] | Δ nDCG@10 vs previous row [95% CI] |",
        "|---|---:|---:|---:|",
    ]
    for row in rows:
        vb = row.get("delta_vs_bm25_only") or {}
        vp = row.get("delta_vs_previous") or {}
        prev = f" (vs {vp['reference']})" if vp.get("reference") else ""
        lines.append(
            f"| {row['config']} | {_delta(vb.get('ndcg@10'))} | {_delta(vb.get('recall@10'))} | {_delta(vp.get('ndcg@10'))}{prev} |"
        )
    full = _rows(blob).get(FULL)
    if full:
        lines += [
            "",
            f"Per category, {FULL} (n is the number of gold questions; no intervals at these sizes):",
            "",
            "| category | n | nDCG@10 | Recall@10 | Recall@50 |",
            "|---|---:|---:|---:|---:|",
        ]
        for cat, sc in full["retrieval"]["by_category"].items():
            lines.append(f"| {cat} | {int(sc['n'])} | {sc['ndcg@10']:.3f} | {sc.get('recall@10', 0):.3f} | {sc['recall@50']:.3f} |")
    cat_lines = _category_delta_lines(rows)
    if cat_lines:
        lines += ["", "Per-category paired deltas vs parent, where the mechanism targets one category (small n, no claim beyond the slice):", ""] + cat_lines
    if boot:
        lines += [
            "",
            f"Intervals: {boot.get('method')}; {boot.get('n_boot')} resamples, seed {boot.get('seed')}, "
            f"{boot.get('rng')}. Results file sha {blob.get('git_sha')}, corpus sha {str(blob.get('corpus_sha256', ''))[:12]}.",
        ]
    return "\n".join(lines)


def _category_delta_lines(rows: list[dict]) -> list[str]:
    out = []
    for row in rows:
        cd = row.get("delta_vs_parent_by_category")
        if not cd:
            continue
        flag = " (small n)" if cd.get("small_n") else ""
        out.append(
            f"- `{row['config']}` vs `{cd['reference']}` on `{cd['category']}`, n = {cd['n']}{flag}: "
            f"nDCG@10 {_delta(cd.get('ndcg@10'))} ({_zero_note(cd.get('ndcg@10'))}), Recall@10 {_delta(cd.get('recall@10'))}."
        )
    return out


def demo_stats(blob: dict) -> str:
    """Stat tiles for doc/demo.html: the two headline metrics of the full pipeline, and the fixture size."""
    full = _rows(blob).get(FULL)
    if full is None:
        return '<div class="stat"><b>—</b><span>no full-pipeline row in main.json</span></div>'
    return "\n".join(
        [
            f'      <div class="stat"><b>{_ci(full, "ndcg@10")}</b><span>nDCG@10, full pipeline (95% CI)</span></div>',
            f'      <div class="stat"><b>{_ci(full, "recall@10")}</b><span>Recall@10, full pipeline (95% CI)</span></div>',
            f'      <div class="stat"><b>{blob["n_gold"]}</b><span>scripted questions, {blob["n_files"]} frozen files</span></div>',
        ]
    )


def _beats(block: dict | None) -> str:
    """'yes' when the paired delta's interval is above zero, 'no' when below, 'tie' when it covers zero."""
    if not block:
        return "n/a"
    if block["lo"] > 0.0:
        return "yes"
    if block["hi"] < 0.0:
        return "no"
    return "tie"


def _models(row: dict) -> str:
    m = row.get("models") or {}
    parts = []
    e = m.get("embedder") or {}
    if e.get("neural"):
        parts.append(f"{e['model']}@{(e.get('revision') or '?')[:7]}")
    r = m.get("reranker") or {}
    if r.get("neural") and r.get("loaded"):
        parts.append(f"{r['model']}@{(r.get('revision') or '?')[:7]}")
    return ", ".join(parts) if parts else "hash / overlap"


def _device(blob: dict) -> str:
    d = blob.get("device") or {}
    return f"{d.get('device', '?')} ({d.get('device_name', '?')}), torch {d.get('torch', '?')}, sentence-transformers {d.get('sentence_transformers', '?')}"


def _parent_of(row: dict) -> str:
    return (row.get("settings") or {}).get("parent") or (row.get("delta_vs_previous") or {}).get("reference") or "—"


def neural_table(blob: dict | None) -> str:
    if not blob:
        return f"_{NEURAL_FILE} is missing; run `make bench-neural`._"
    rows = list(blob.get("results", []))
    by = _rows(blob)
    lines = [
        f"Fixture v1 with real models (`make bench-neural`, {_device(blob)}; results sha {blob.get('git_sha')}). "
        f"Each row names its parent (one change away); the paired delta is against that parent. "
        f"Wall time is the whole row after a warm-up query.",
        "",
        "| config | parent | models (revision) | nDCG@10 [95% CI] | Recall@10 [95% CI] | Δ nDCG@10 vs parent [95% CI] | Δ vs bm25_only | beats BM25? | wall s |",
        "|---|---|---|---:|---:|---:|---:|:---:|---:|",
    ]
    for row in rows:
        dp = (row.get("delta_vs_previous") or {}).get("ndcg@10")
        db = (row.get("delta_vs_bm25_only") or {}).get("ndcg@10")
        lines.append(
            f"| {row['config']} | {_parent_of(row)} | {_models(row)} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | "
            f"{_delta(dp)} | {_delta(db)} | {_beats(db)} | {row.get('wall_ms', 0) / 1000:.1f} |"
        )
    parts = []
    for name, label in (
        ("hybrid@bge-small", "Hybrid RRF over dense bge-small"),
        ("hybrid+bge-rerank@bge-small", "bge-reranker-v2-m3 over that hybrid"),
        ("hybrid+bge-rerank+router@bge-small", "Router on top of the reranked hybrid"),
        ("hybrid+bge-rerank+router+staleness@bge-small", "Staleness Tier 1 on top of that"),
    ):
        row = by.get(name)
        if not row:
            continue
        d = (row.get("delta_vs_previous") or {}).get("ndcg@10")
        parts.append(f"{label}: nDCG@10 {_delta(d)} ({_zero_note(d)}).")
    comps = (blob.get("bootstrap") or {}).get("comparisons") or []
    for c in comps:
        if c.get("row") == "hybrid+bge-rerank@bge-small" and c.get("other") == "hybrid+bge-rerank@hash":
            d = c.get("ndcg@10")
            a, b = by.get("hybrid+bge-rerank@bge-small"), by.get("hybrid+bge-rerank@hash")
            if d and a and b:
                n_chunks = a.get("n_chunks", "?")
                k = (a.get("settings") or {}).get("retrieve_k", "?")
                parts.append(
                    f"With the reranker on, the first stage stops mattering on this fixture: bge-small + reranker "
                    f"{a['retrieval']['ndcg@10']:.3f} vs hash + reranker {b['retrieval']['ndcg@10']:.3f}, paired delta "
                    f"{_delta(d)} ({_zero_note(d)}), because the reranker rescores {k} of {n_chunks} chunks."
                )
    if parts:
        lines += ["", " ".join(parts)]
    cat_lines = _category_delta_lines(rows)
    if cat_lines:
        lines += ["", "Per-category paired deltas vs parent (small n):", ""] + cat_lines
    return "\n".join(lines)


def _rerank_settings(row: dict) -> str:
    st = row.get("settings") or {}
    if not st.get("reranker"):
        return "—"
    ml = st.get("max_length") or "uncapped"
    return f"{st.get('precision', 'fp32')} / {ml} / top {st.get('rerank_top')}"


