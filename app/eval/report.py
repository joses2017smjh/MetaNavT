"""Render the README's benchmark blocks from the committed baseline.

    python -m app.eval.report            # print the blocks
    python -m app.eval.report --write    # replace the marked blocks in README.md and doc/demo.html
    python -m app.eval.report --check    # exit 1 if any marked block differs

Every number the README and the demo page state about the fixture benchmark
comes from bench/results/main.json through this module. The blocks are
delimited by HTML comments so tests/eval/test_readme_numbers.py can assert the
files never drift from the results file.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

FULL = "hybrid+rerank+router+staleness"
ROUTER_OFF, ROUTER_ON = "hybrid+rerank", "hybrid+rerank+router"
REFERENCE = "bm25_only"
BLOCKS = ("bench-headline", "bench-table", "demo-stats", "bench-neural", "bench-beir", "bench-parity")
FILES = {"README.md": ("bench-headline", "bench-table", "bench-neural", "bench-beir", "bench-parity"), "doc/demo.html": ("demo-stats",)}
NEURAL_FILE = "bench/results/neural.json"
BEIR_FILE = "bench/results/beir_scifact.json"
PARITY_FILE = "bench/results/parity.json"
SOURCES = {
    "bench-headline": "bench/results/main.json",
    "bench-table": "bench/results/main.json",
    "demo-stats": "bench/results/main.json",
    "bench-neural": NEURAL_FILE,
    "bench-beir": BEIR_FILE,
    "bench-parity": PARITY_FILE,
}
NEURAL_REFERENCE = "bm25_only"
ADDED_COMPONENTS = ("hybrid+rerank", "hybrid+rerank+router", FULL)  # the ablation chain after plain RRF


def _start(name: str) -> str:
    return f"<!-- {name}:start (generated by `make bench-table` from {SOURCES.get(name, 'bench/results/main.json')}; do not edit by hand) -->"


def _end(name: str) -> str:
    return f"<!-- {name}:end -->"


def _rows(blob: dict) -> dict[str, dict]:
    return {row["config"]: row for row in blob.get("results", [])}


def _ci(row: dict | None, metric: str) -> str:
    block = (row or {}).get("ci", {}).get(metric) if row else None
    if not block:
        return "—"
    return f"{block['mean']:.3f} [{block['lo']:.3f}, {block['hi']:.3f}]"


def _delta(block: dict | None) -> str:
    if not block:
        return "—"
    return f"{block['delta']:+.3f} [{block['lo']:+.3f}, {block['hi']:+.3f}]"


def _zero_note(block: dict | None) -> str:
    if not block:
        return ""
    return "the interval covers zero" if block["lo"] <= 0.0 <= block["hi"] else "the interval excludes zero"


def components_excluding_zero(blob: dict) -> list[str]:
    """Added components whose nDCG@10 gain over the previous row has a CI above zero."""
    rows = _rows(blob)
    out = []
    for name in ADDED_COMPONENTS:
        block = ((rows.get(name) or {}).get("delta_vs_previous") or {}).get("ndcg@10")
        if block and block["lo"] > 0.0:
            out.append(name.split("+")[-1])
    return out


def headline(blob: dict) -> str:
    rows = _rows(blob)
    full, bm25 = rows.get(FULL), rows.get(REFERENCE)
    if full is None or bm25 is None:
        return f"Fixture benchmark: {len(rows)} configs (no {FULL} / {REFERENCE} rows to summarise)."
    r_full, r_bm25 = full["retrieval"], bm25["retrieval"]
    d_bm25 = (full.get("delta_vs_bm25_only") or {})
    d_prev = (full.get("delta_vs_previous") or {})
    parts = [
        f"On the frozen fixture ({blob['n_gold']} questions over {blob['n_files']} files; hash embeddings, "
        f"overlap reranker) the full pipeline scores nDCG@10 {_ci(full, 'ndcg@10')} and Recall@10 "
        f"{_ci(full, 'recall@10')}; BM25 alone scores nDCG@10 {_ci(bm25, 'ndcg@10')} and Recall@10 "
        f"{_ci(bm25, 'recall@10')}.",
        f"Paired delta, full pipeline minus BM25: nDCG@10 {_delta(d_bm25.get('ndcg@10'))} "
        f"({_zero_note(d_bm25.get('ndcg@10'))}), Recall@10 {_delta(d_bm25.get('recall@10'))} "
        f"({_zero_note(d_bm25.get('recall@10'))}).",
    ]
    if d_prev.get("reference") == ROUTER_ON:
        parts.append(
            f"Staleness Tier 1 on vs off: nDCG@10 {_delta(d_prev.get('ndcg@10'))} "
            f"({_zero_note(d_prev.get('ndcg@10'))})."
        )
    excl = components_excluding_zero(blob)
    parts.append(
        "Of the added components (rerank, router, staleness), the nDCG@10 gain over the previous row "
        f"that excludes zero: {', '.join(excl) if excl else 'none'}."
    )
    off, on = rows.get(ROUTER_OFF), rows.get(ROUTER_ON)
    if off and on:
        cat_off = off["retrieval"]["by_category"].get("exact_path", {})
        cat_on = on["retrieval"]["by_category"].get("exact_path", {})
        if cat_off and cat_on:
            parts.append(
                f"The router's exact-path gain, nDCG@10 {cat_off['ndcg@10']:.3f} → {cat_on['ndcg@10']:.3f}, "
                f"rests on n = {int(cat_on['n'])} questions."
            )
    rand = r_full.get("random_recall@50")
    if rand is not None:
        parts.append(
            f"Recall@50 is {r_full['recall@50']:.3f} against {rand:.3f} for a random list of the same length: "
            f"with {r_full['mean_unique_paths@50']:.0f} unique files in a top-50 over {blob['n_files']}, "
            f"that metric mostly measures list length."
        )
    return " ".join(parts)


def table(blob: dict) -> str:
    rows = list(blob.get("results", []))
    boot = blob.get("bootstrap") or {}
    lines = [
        "| config | nDCG@10 [95% CI] | Recall@10 [95% CI] | random list @10 | Recall@50 | random list @50 | unique files in top 50 | MRR@10 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        r = row["retrieval"]
        rand50 = r.get("random_recall@50")
        rand10 = r.get("random_recall@10")
        fmt = lambda v: "—" if v is None else f"{v:.3f}"  # noqa: E731
        lines.append(
            f"| {row['config']} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | {fmt(rand10)} | {r['recall@50']:.3f} | "
            f"{fmt(rand50)} | {r.get('mean_unique_paths@50', 0):.1f} | {r['mrr@10']:.3f} |"
        )
    lines += [
        "",
        "Paired deltas (same bootstrap resamples for both sides):",
        "",
        "| config | Δ nDCG@10 vs bm25_only [95% CI] | Δ Recall@10 vs bm25_only [95% CI] | Δ nDCG@10 vs previous row [95% CI] |",
        "|---|---:|---:|---:|",
    ]
    for row in rows:
        vb = row.get("delta_vs_bm25_only") or {}
        vp = row.get("delta_vs_previous") or {}
        prev = f" (vs {vp['reference']})" if vp.get("reference") else ""
        lines.append(
            f"| {row['config']} | {_delta(vb.get('ndcg@10'))} | {_delta(vb.get('recall@10'))} | {_delta(vp.get('ndcg@10'))}{prev} |"
        )
    full = _rows(blob).get(FULL)
    if full:
        lines += [
            "",
            f"Per category, {FULL} (n is the number of gold questions; no intervals at these sizes):",
            "",
            "| category | n | nDCG@10 | Recall@10 | Recall@50 |",
            "|---|---:|---:|---:|---:|",
        ]
        for cat, sc in full["retrieval"]["by_category"].items():
            lines.append(f"| {cat} | {int(sc['n'])} | {sc['ndcg@10']:.3f} | {sc.get('recall@10', 0):.3f} | {sc['recall@50']:.3f} |")
    if boot:
        lines += [
            "",
            f"Intervals: {boot.get('method')}; {boot.get('n_boot')} resamples, seed {boot.get('seed')}, "
            f"{boot.get('rng')}. Results file sha {blob.get('git_sha')}, corpus sha {str(blob.get('corpus_sha256', ''))[:12]}.",
        ]
    return "\n".join(lines)


def demo_stats(blob: dict) -> str:
    """Stat tiles for doc/demo.html: the two headline metrics of the full pipeline, and the fixture size."""
    full = _rows(blob).get(FULL)
    if full is None:
        return '<div class="stat"><b>—</b><span>no full-pipeline row in main.json</span></div>'
    return "\n".join(
        [
            f'      <div class="stat"><b>{_ci(full, "ndcg@10")}</b><span>nDCG@10, full pipeline (95% CI)</span></div>',
            f'      <div class="stat"><b>{_ci(full, "recall@10")}</b><span>Recall@10, full pipeline (95% CI)</span></div>',
            f'      <div class="stat"><b>{blob["n_gold"]}</b><span>hand-built questions, {blob["n_files"]} frozen files</span></div>',
        ]
    )


def _beats(block: dict | None) -> str:
    """'yes' when the paired delta's interval is above zero, 'no' when below, 'tie' when it covers zero."""
    if not block:
        return "n/a"
    if block["lo"] > 0.0:
        return "yes"
    if block["hi"] < 0.0:
        return "no"
    return "tie"


def _models(row: dict) -> str:
    m = row.get("models") or {}
    parts = []
    e = m.get("embedder") or {}
    if e.get("neural"):
        parts.append(f"{e['model']}@{(e.get('revision') or '?')[:7]}")
    r = m.get("reranker") or {}
    if r.get("neural") and r.get("loaded"):
        parts.append(f"{r['model']}@{(r.get('revision') or '?')[:7]}")
    return ", ".join(parts) if parts else "hash / overlap"


def _device(blob: dict) -> str:
    d = blob.get("device") or {}
    return f"{d.get('device', '?')} ({d.get('device_name', '?')}), torch {d.get('torch', '?')}, sentence-transformers {d.get('sentence_transformers', '?')}"


def neural_table(blob: dict | None) -> str:
    if not blob:
        return f"_{NEURAL_FILE} is missing; run `make bench-neural`._"
    rows = list(blob.get("results", []))
    by = _rows(blob)
    lines = [
        f"Fixture v1 with real models (`make bench-neural`, {_device(blob)}; results sha {blob.get('git_sha')}). "
        f"Paired deltas vs the same bm25_only row; same bootstrap as above.",
        "",
        "| config | models (revision) | nDCG@10 [95% CI] | Recall@10 [95% CI] | Recall@50 | Δ nDCG@10 vs bm25_only [95% CI] | beats BM25? | wall s |",
        "|---|---|---:|---:|---:|---:|:---:|---:|",
    ]
    for row in rows:
        r = row["retrieval"]
        d = (row.get("delta_vs_bm25_only") or {}).get("ndcg@10")
        lines.append(
            f"| {row['config']} | {_models(row)} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | {r['recall@50']:.3f} | "
            f"{_delta(d)} | {_beats(d)} | {row.get('wall_ms', 0) / 1000:.1f} |"
        )
    hyb = by.get("hybrid@bge-small")
    rer = by.get("hybrid+bge-rerank@bge-small")
    full = next((by[k] for k in by if k.startswith("hybrid+bge-rerank+router+staleness")), None)
    parts = []
    if hyb:
        d = (hyb.get("delta_vs_bm25_only") or {}).get("ndcg@10")
        parts.append(f"Hybrid RRF with bge-small vs BM25 alone: nDCG@10 {_delta(d)} ({_zero_note(d)}).")
    if rer:
        d = (rer.get("delta_vs_bm25_only") or {}).get("ndcg@10")
        parts.append(f"Adding bge-reranker-v2-m3: {_delta(d)} vs BM25 ({_zero_note(d)}).")
    if full and rer:
        d = (full.get("delta_vs_previous") or {}).get("ndcg@10")
        parts.append(f"Router + staleness on top of the reranked hybrid: {_delta(d)} ({_zero_note(d)}).")
    if parts:
        lines += ["", " ".join(parts)]
    return "\n".join(lines)


def beir_table(blob: dict | None) -> str:
    if not blob:
        return f"_{BEIR_FILE} is missing; run `make bench-beir`._"
    pub = blob.get("published", {})
    lines = [
        f"BEIR SciFact test split (`make bench-beir`): {blob.get('n_docs')} documents, {blob.get('n_queries')} queries; "
        f"{_device(blob)}; results sha {blob.get('git_sha')}. Published BM25 nDCG@10 = {pub.get('bm25_ndcg@10'):.3f} "
        f"({pub.get('analyzer')}).",
        "",
        "| config | models (revision) | nDCG@10 [95% CI] | Recall@10 [95% CI] | Recall@100 [95% CI] | Δ nDCG@10 vs bm25 [95% CI] | beats BM25? | p50 / p95 ms per query |",
        "|---|---|---:|---:|---:|---:|:---:|---:|",
    ]
    for row in blob.get("results", []):
        d = (row.get("delta_vs_bm25") or {}).get("ndcg@10")
        lat = (row.get("latency") or {}).get("total") or {}
        lines.append(
            f"| {row['config']} | {_models(row)} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | {_ci(row, 'recall@100')} | "
            f"{_delta(d)} | {_beats(d)} | {lat.get('p50_ms', '—')} / {lat.get('p95_ms', '—')} |"
        )
    by = _rows(blob)
    parts = []
    bm25 = by.get("bm25")
    if bm25 and bm25.get("vs_published"):
        vp = bm25["vs_published"]
        parts.append(f"Our BM25 with the BEIR analyzer scores nDCG@10 {bm25['retrieval']['ndcg@10']:.3f} against the published {vp['published_bm25_ndcg@10']:.3f} ({vp['delta']:+.3f}).")
    for name, label in (("hybrid@bge-small", "Hybrid RRF"), ("hybrid+bge-rerank@bge-small", "Hybrid + bge-reranker-v2-m3")):
        row = by.get(name)
        if row:
            d = (row.get("delta_vs_bm25") or {}).get("ndcg@10")
            parts.append(f"{label} vs BM25: nDCG@10 {_delta(d)} ({_zero_note(d)}).")
    if parts:
        lines += ["", " ".join(parts)]
    return "\n".join(lines)


def parity_table(blob: dict | None) -> str:
    if not blob:
        return f"_{PARITY_FILE} is missing; run `make parity` against a running API._"
    lines = [
        f"Same 136 questions, same metrics, same paired bootstrap (`make parity`, results sha {blob.get('git_sha')}). "
        f"The in-memory row is the bench harness with the switches the API serves in CI: hybrid RRF, router on, "
        f"staleness Tier 1 on, no reranker, hash embeddings. The API row is POST /api/retrieve/ over Postgres + pgvector "
        f"(one SQL round trip, app/database/sql/hybrid_tsrank.sql).",
        "",
        "| row | nDCG@10 [95% CI] | Recall@10 [95% CI] | Recall@50 | lexical leg | chunker | p50 / p95 ms per query |",
        "|---|---:|---:|---:|---|---|---:|",
    ]
    for row in blob.get("results", []):
        lat = row.get("latency") or {}
        e2e = lat.get("e2e") or lat.get("vector_search") or lat.get("bm25") or {}
        is_api = row["config"].startswith("api")
        lex = (row.get("settings") or {}).get("bm25_backend") if is_api else "in-memory Okapi BM25"
        chunker = "SentenceSplitter(512, 50)" if is_api else "app/chunking (structure-aware)"
        lines.append(
            f"| {row['config']} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | {row['retrieval']['recall@50']:.3f} | "
            f"{lex or '—'} | {chunker} | {e2e.get('p50_ms', '—')} / {e2e.get('p95_ms', '—')} |"
        )
    g = blob.get("gate") or {}
    d = g.get("paired_delta_api_minus_in_memory") or {}
    if g:
        lines += [
            "",
            f"Gate: nDCG@10 gap, API minus in-memory, {g.get('gap', 0):+.4f} with paired 95% CI "
            f"{_delta(d) if d else '—'} ({_zero_note(d) if d else 'no interval'}); tolerance {g.get('tolerance')}; "
            f"{'passes' if g.get('ok') else 'FAILS'}. The API's e2e latency is client-measured over HTTP on the machine that produced the results file; "
            f"the in-memory figure is the search stage only.",
        ]
    return "\n".join(lines)


def _load(root: Path | None, rel: str) -> dict | None:
    if root is None:
        return None
    path = root / rel
    return json.loads(path.read_text()) if path.exists() else None


def render(blob: dict, root: Path | None = None) -> dict[str, str]:
    root = root if root is not None else Path(__file__).resolve().parents[2]
    return {
        "bench-headline": headline(blob),
        "bench-table": table(blob),
        "demo-stats": demo_stats(blob),
        "bench-neural": neural_table(_load(root, NEURAL_FILE)),
        "bench-beir": beir_table(_load(root, BEIR_FILE)),
        "bench-parity": parity_table(_load(root, PARITY_FILE)),
    }


def wrap(name: str, body: str) -> str:
    return f"{_start(name)}\n{body}\n{_end(name)}"


def check(text: str, blob: dict, names: tuple[str, ...] = ("bench-headline", "bench-table"), root: Path | None = None) -> list[str]:
    """Problems with a file's generated blocks (empty = in sync)."""
    problems: list[str] = []
    rendered = render(blob, root)
    for name in names:
        expected = wrap(name, rendered[name])
        if expected in text:
            continue
        if _start(name) not in text or _end(name) not in text:
            problems.append(f"{name}: markers missing")
        else:
            problems.append(f"{name}: block differs from `make bench-table` output")
    return problems


def write(text: str, blob: dict, names: tuple[str, ...], root: Path | None = None) -> str:
    """Replace each marked block in `text` with its rendered version (markers must exist)."""
    rendered = render(blob, root)
    for name in names:
        start, end = text.find(_start(name)), text.find(_end(name))
        if start < 0 or end < 0 or end < start:
            raise ValueError(f"{name}: markers missing; add them once by hand")
        text = text[:start] + wrap(name, rendered[name]) + text[end + len(_end(name)):]
    return text


def check_files(root: Path, blob: dict) -> list[str]:
    problems: list[str] = []
    for rel, names in FILES.items():
        problems += [f"{rel}: {p}" for p in check((root / rel).read_text(), blob, names, root=root)]
    return problems


def main(argv: list[str] | None = None) -> int:
    root = Path(__file__).resolve().parents[2]
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", type=Path, default=root / "bench" / "results" / "main.json")
    p.add_argument("--check", action="store_true", help="verify README.md and doc/demo.html instead of printing")
    p.add_argument("--write", action="store_true", help="replace the marked blocks in README.md and doc/demo.html")
    args = p.parse_args(argv)
    blob = json.loads(args.results.read_text())
    if args.write:
        for rel, names in FILES.items():
            path = root / rel
            path.write_text(write(path.read_text(), blob, names, root=root))
            print(f"updated {rel}: {', '.join(names)}")
        return 0
    if args.check:
        problems = check_files(root, blob)
        for line in problems:
            print(f"drift: {line}")
        if not problems:
            print(f"generated blocks in {', '.join(FILES)} are in sync with {args.results}")
        return 1 if problems else 0
    for name, body in render(blob, root).items():
        print(wrap(name, body))
        print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
