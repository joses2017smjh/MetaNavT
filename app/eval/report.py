"""Render the README's benchmark blocks from the committed baseline.

    python -m app.eval.report                    # print the blocks
    python -m app.eval.report --check README.md  # exit 1 if the README's blocks differ

Every number the README states about the fixture benchmark comes from
bench/results/main.json through this module. The blocks are delimited by HTML
comments so tests/eval/test_readme_numbers.py can assert the README never drifts
from the results file.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

FULL = "hybrid+rerank+router+staleness"
ROUTER_OFF, ROUTER_ON = "hybrid+rerank", "hybrid+rerank+router"
REFERENCE = "bm25_only"
BLOCKS = ("bench-headline", "bench-table")


def _start(name: str) -> str:
    return f"<!-- {name}:start (generated by `make bench-table` from bench/results/main.json; do not edit by hand) -->"


def _end(name: str) -> str:
    return f"<!-- {name}:end -->"


def _rows(blob: dict) -> dict[str, dict]:
    return {row["config"]: row for row in blob.get("results", [])}


def _ci(row: dict | None, metric: str) -> str:
    block = (row or {}).get("ci", {}).get(metric) if row else None
    if not block:
        return "—"
    return f"{block['mean']:.3f} [{block['lo']:.3f}, {block['hi']:.3f}]"


def _delta(block: dict | None) -> str:
    if not block:
        return "—"
    return f"{block['delta']:+.3f} [{block['lo']:+.3f}, {block['hi']:+.3f}]"


def _zero_note(block: dict | None) -> str:
    if not block:
        return ""
    return "the interval covers zero" if block["lo"] <= 0.0 <= block["hi"] else "the interval excludes zero"


def headline(blob: dict) -> str:
    rows = _rows(blob)
    full, bm25 = rows.get(FULL), rows.get(REFERENCE)
    if full is None or bm25 is None:
        return f"Fixture benchmark: {len(rows)} configs (no {FULL} / {REFERENCE} rows to summarise)."
    r_full, r_bm25 = full["retrieval"], bm25["retrieval"]
    d_bm25 = (full.get("delta_vs_bm25_only") or {})
    d_prev = (full.get("delta_vs_previous") or {})
    parts = [
        f"On the frozen fixture ({blob['n_gold']} questions over {blob['n_files']} files; hash embeddings, "
        f"overlap reranker) the full pipeline scores nDCG@10 {_ci(full, 'ndcg@10')} and Recall@10 "
        f"{_ci(full, 'recall@10')}; BM25 alone scores nDCG@10 {_ci(bm25, 'ndcg@10')} and Recall@10 "
        f"{_ci(bm25, 'recall@10')}.",
        f"Paired delta, full pipeline minus BM25: nDCG@10 {_delta(d_bm25.get('ndcg@10'))} "
        f"({_zero_note(d_bm25.get('ndcg@10'))}), Recall@10 {_delta(d_bm25.get('recall@10'))} "
        f"({_zero_note(d_bm25.get('recall@10'))}).",
    ]
    if d_prev.get("reference") == ROUTER_ON:
        parts.append(
            f"Staleness Tier 1 on vs off: nDCG@10 {_delta(d_prev.get('ndcg@10'))} "
            f"({_zero_note(d_prev.get('ndcg@10'))})."
        )
    off, on = rows.get(ROUTER_OFF), rows.get(ROUTER_ON)
    if off and on:
        cat_off = off["retrieval"]["by_category"].get("exact_path", {})
        cat_on = on["retrieval"]["by_category"].get("exact_path", {})
        if cat_off and cat_on:
            parts.append(
                f"The router's exact-path gain, nDCG@10 {cat_off['ndcg@10']:.3f} → {cat_on['ndcg@10']:.3f}, "
                f"rests on n = {int(cat_on['n'])} questions."
            )
    rand = r_full.get("random_recall@50")
    if rand is not None:
        parts.append(
            f"Recall@50 is {r_full['recall@50']:.3f} against {rand:.3f} for a random list of the same length: "
            f"with {r_full['mean_unique_paths@50']:.0f} unique files in a top-50 over {blob['n_files']}, "
            f"that metric mostly measures list length."
        )
    return " ".join(parts)


def table(blob: dict) -> str:
    rows = list(blob.get("results", []))
    boot = blob.get("bootstrap") or {}
    lines = [
        "| config | nDCG@10 [95% CI] | Recall@10 [95% CI] | Recall@50 | random list, same length | unique files in top 50 | MRR@10 |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        r = row["retrieval"]
        rand = r.get("random_recall@50")
        lines.append(
            f"| {row['config']} | {_ci(row, 'ndcg@10')} | {_ci(row, 'recall@10')} | {r['recall@50']:.3f} | "
            f"{'—' if rand is None else f'{rand:.3f}'} | {r.get('mean_unique_paths@50', 0):.1f} | {r['mrr@10']:.3f} |"
        )
    lines += [
        "",
        "Paired deltas (same bootstrap resamples for both sides):",
        "",
        "| config | Δ nDCG@10 vs bm25_only [95% CI] | Δ Recall@10 vs bm25_only [95% CI] | Δ nDCG@10 vs previous row [95% CI] |",
        "|---|---:|---:|---:|",
    ]
    for row in rows:
        vb = row.get("delta_vs_bm25_only") or {}
        vp = row.get("delta_vs_previous") or {}
        prev = f" (vs {vp['reference']})" if vp.get("reference") else ""
        lines.append(
            f"| {row['config']} | {_delta(vb.get('ndcg@10'))} | {_delta(vb.get('recall@10'))} | {_delta(vp.get('ndcg@10'))}{prev} |"
        )
    full = _rows(blob).get(FULL)
    if full:
        lines += [
            "",
            f"Per category, {FULL} (n is the number of gold questions; no intervals at these sizes):",
            "",
            "| category | n | nDCG@10 | Recall@10 | Recall@50 |",
            "|---|---:|---:|---:|---:|",
        ]
        for cat, sc in full["retrieval"]["by_category"].items():
            lines.append(f"| {cat} | {int(sc['n'])} | {sc['ndcg@10']:.3f} | {sc.get('recall@10', 0):.3f} | {sc['recall@50']:.3f} |")
    if boot:
        lines += [
            "",
            f"Intervals: {boot.get('method')}; {boot.get('n_boot')} resamples, seed {boot.get('seed')}, "
            f"{boot.get('rng')}. Results file sha {blob.get('git_sha')}, corpus sha {str(blob.get('corpus_sha256', ''))[:12]}.",
        ]
    return "\n".join(lines)


def render(blob: dict) -> dict[str, str]:
    return {"bench-headline": headline(blob), "bench-table": table(blob)}


def wrap(name: str, body: str) -> str:
    return f"{_start(name)}\n{body}\n{_end(name)}"


def check(readme_text: str, blob: dict) -> list[str]:
    """Problems with the README's generated blocks (empty = in sync)."""
    problems: list[str] = []
    for name, body in render(blob).items():
        expected = wrap(name, body)
        if expected in readme_text:
            continue
        if _start(name) not in readme_text or _end(name) not in readme_text:
            problems.append(f"{name}: markers missing from README")
        else:
            problems.append(f"{name}: README block differs from `make bench-table` output")
    return problems


def main(argv: list[str] | None = None) -> int:
    root = Path(__file__).resolve().parents[2]
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", type=Path, default=root / "bench" / "results" / "main.json")
    p.add_argument("--check", type=Path, default=None, help="README to verify instead of printing")
    args = p.parse_args(argv)
    blob = json.loads(args.results.read_text())
    if args.check is None:
        for name, body in render(blob).items():
            print(wrap(name, body))
            print()
        return 0
    problems = check(args.check.read_text(), blob)
    for line in problems:
        print(f"drift: {line}")
    print("README blocks in sync with", args.results) if not problems else None
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
